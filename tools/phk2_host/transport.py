"""Future semantic transport seam. Only the offline mock is implemented."""
from typing import Protocol, Iterable
from runtime import Result
class Transport(Protocol):
    def load_job(self, descriptor: bytes) -> int: ...
    def start_range(self, generation: int, start: int, count: int, range_id: int) -> Iterable[Result]: ...
    def status(self): ...
    def read_result(self, generation: int, range_id: int) -> Iterable[Result]: ...
    def abort(self, generation: int, range_id: int) -> None: ...
